def set_heading_styles(doc):
    for style_name, size, color in [
        ("Title", 22, (0, 51, 102)),
        ("Heading 1", 16, (0, 51, 102)),
        ("Heading 2", 14, (0, 82, 136)),
        ("Heading 3", 12, (0, 82, 136)),
    ]:
        try:
            style = doc.styles[style_name]
            style.font.size = Pt(size)
            style.font.color.rgb = RGBColor(*color)
            style.font.bold = True
        except Exception:
            pass


def add_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = h
        for run in hdr[i].paragraphs[0].runs:
            run.bold = True
    for r in rows:
        cells = table.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = str(v)
    doc.add_paragraph()
    return table


def add_figure(doc, image_path, caption, width_inches=5.5):
    if not os.path.exists(image_path):
        doc.add_paragraph(f"[Figure not found: {image_path}]")
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(image_path, width=Inches(width_inches))
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in cap.runs:
        r.italic = True
        r.font.size = Pt(10)


def add_bold_para(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(11)
    return p


